#!/usr/bin/env python3
"""Build a GitHub Pages-ready snapshot of the read-only DB viewer."""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import tempfile
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from server import (
    DEFAULT_DB,
    DEFAULT_ERD,
    DEFAULT_MMD,
    PUBLIC_SCHEMA_ONLY_TABLES,
    STATIC_DIR,
    Database,
)


PROJECT_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = PROJECT_ROOT / "docs"
BUILD_MARKER = ".db-viewer-static"


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def write_json(path: Path, payload: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )


def write_entity_collection(
    root: Path,
    collection: str,
    items: list[dict[str, Any]],
    detail_loader,
) -> None:
    write_json(root / "data" / collection / "index.json", {"items": items})
    for item in items:
        code = item["code"]
        detail = detail_loader(code)
        if detail is None:
            raise RuntimeError(f"Missing detail for {collection}/{code}")
        write_json(root / "data" / collection / f"{code}.json", detail)


def export_table(database: Database, name: str, schema_only: bool = False) -> dict[str, Any]:
    if schema_only:
        schema = database.table_schema(name)
        return {
            "name": name,
            "kind": schema["kind"],
            "columns": schema["columns"],
            "rows": [],
            "total": None,
            "restricted": True,
            "visibility": "local_only",
        }
    rows: list[dict[str, Any]] = []
    offset = 0
    first_page: dict[str, Any] | None = None
    while True:
        page = database.table_data(name, limit=100, offset=offset)
        first_page = first_page or page
        rows.extend(page["rows"])
        offset += len(page["rows"])
        if not page["rows"] or offset >= page["total"]:
            break
    assert first_page is not None
    return {
        "name": first_page["name"],
        "kind": first_page["kind"],
        "columns": first_page["columns"],
        "rows": rows,
        "total": len(rows),
    }


def validate_output_path(output: Path) -> None:
    resolved = output.resolve()
    forbidden = {PROJECT_ROOT.resolve(), Path("/").resolve(), STATIC_DIR.resolve()}
    if resolved in forbidden:
        raise ValueError(f"Unsafe output path: {resolved}")
    if resolved.exists() and not (resolved / BUILD_MARKER).is_file():
        raise ValueError(
            f"Refusing to replace non-generated directory: {resolved}. "
            f"Remove it manually or choose another --output."
        )


def build_site(database_path: Path, output: Path) -> Path:
    database_path = database_path.resolve()
    output = output.resolve()
    validate_output_path(output)
    database = Database(database_path)
    before_checksum = sha256(database_path)
    output.parent.mkdir(parents=True, exist_ok=True)
    temp_root = Path(tempfile.mkdtemp(prefix=".db-viewer-build-", dir=output.parent))

    try:
        (temp_root / "static").mkdir(parents=True)
        for filename in ("app.js", "styles.css"):
            shutil.copy2(STATIC_DIR / filename, temp_root / "static" / filename)
        shutil.copy2(STATIC_DIR / "index.html", temp_root / "index.html")
        shutil.copy2(STATIC_DIR / "index.html", temp_root / "404.html")
        (temp_root / "static" / "config.js").write_text(
            'window.DB_VIEWER_CONFIG = { mode: "static", dataBase: "./data" };\n',
            encoding="utf-8",
        )
        (temp_root / ".nojekyll").write_text("", encoding="utf-8")
        (temp_root / BUILD_MARKER).write_text(
            "Generated by db-viewer/build_static.py; safe to replace.\n",
            encoding="utf-8",
        )

        assets = temp_root / "assets"
        assets.mkdir()
        shutil.copy2(DEFAULT_ERD, assets / "erd.svg")
        shutil.copy2(DEFAULT_MMD, assets / "erd.mmd")

        summary = database.summary()
        summary["operational"] = {key: None for key in summary["operational"]}
        summary["operational_visibility"] = "local_only"
        summary["database"] = {
            **summary["database"],
            "mode": "static_snapshot",
            "sha256": before_checksum,
        }
        write_json(temp_root / "data" / "summary.json", summary)
        write_json(
            temp_root / "data" / "health.json",
            {"status": "ok", "database": summary["database"]},
        )

        criteria = database.criteria()
        sources = database.research_sources()
        instruments = database.instruments()
        conditions = database.conditions()
        effects = database.effects()
        write_entity_collection(temp_root, "criteria", criteria, database.criterion)
        write_entity_collection(temp_root, "sources", sources, database.research_source)
        write_entity_collection(temp_root, "instruments", instruments, database.instrument)
        write_entity_collection(temp_root, "conditions", conditions, database.condition)
        write_entity_collection(temp_root, "effects", effects, database.effect)
        write_json(
            temp_root / "data" / "search.json",
            {
                "criteria": criteria,
                "sources": sources,
                "instruments": instruments,
                "conditions": conditions,
                "effects": effects,
            },
        )

        tables = database.tables()
        for item in tables:
            if item["name"] in PUBLIC_SCHEMA_ONLY_TABLES:
                item["row_count"] = None
                item["empty"] = None
                item["restricted"] = True
                item["visibility"] = "local_only"
        write_json(temp_root / "data" / "tables" / "index.json", {"items": tables})
        for item in tables:
            write_json(
                temp_root / "data" / "tables" / f"{item['name']}.json",
                export_table(database, item["name"], item["name"] in PUBLIC_SCHEMA_ONLY_TABLES),
            )

        generated_at = datetime.now(timezone.utc).isoformat(timespec="seconds")
        write_json(
            temp_root / "data" / "build.json",
            {
                "schema_version": 2,
                "generated_at": generated_at,
                "source_database": database_path.name,
                "source_sha256": before_checksum,
                "counts": summary["counts"],
                "static_files": {
                    "criteria_details": len(criteria),
                    "source_details": len(sources),
                    "instrument_details": len(instruments),
                    "condition_details": len(conditions),
                    "effect_details": len(effects),
                    "tables_and_views": len(tables),
                },
            },
        )

        if sha256(database_path) != before_checksum:
            raise RuntimeError("SQLite checksum changed during static export")
        if output.exists():
            shutil.rmtree(output)
        shutil.move(str(temp_root), str(output))
    finally:
        if temp_root.exists():
            shutil.rmtree(temp_root)
    return output


def main() -> None:
    parser = argparse.ArgumentParser(description="Build the TyumGU DB viewer for GitHub Pages")
    parser.add_argument("--db", type=Path, default=DEFAULT_DB, help="Source SQLite database")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT, help="Generated site directory")
    args = parser.parse_args()
    try:
        output = build_site(args.db, args.output)
    except (FileNotFoundError, RuntimeError, ValueError) as error:
        parser.error(str(error))
    print(f"Static site: {output}")
    print(f"Open through HTTP, for example: python3 -m http.server 8001 --directory {output}")


if __name__ == "__main__":
    main()
